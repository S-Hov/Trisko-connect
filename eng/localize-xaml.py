"""Extract static product XAML labels into typed, shared localization properties."""
from pathlib import Path
import re,html,hashlib,json
root=Path(__file__).resolve().parents[1]
strings={}
existing=root/'v2rayN/ServiceLib/Trisko/TriskoStrings.cs'
if existing.exists():
 for key,literal in re.findall(r'public static string ([A-Za-z][A-Za-z0-9_]*) => TriskoLocalization.Text\(("(?:[^"\\]|\\.)*")\);',existing.read_text(encoding='utf-8')):
  strings[key]=json.loads(literal)
for folder in ('v2rayN/v2rayN.Desktop/Trisko','v2rayN/v2rayN.Desktop/Views'):
 for p in (root/folder).glob('*.axaml'):
  s=p.read_text(encoding='utf-8-sig')
  def replace(m):
   value=html.unescape(m[2])
   if not re.search('[А-Яа-яЁё]',value) or value.startswith('{'):return m[0]
   key='S'+hashlib.sha256(value.encode()).hexdigest()[:16]
   strings[key]=value
   return m[1]+'="{x:Static tr:TriskoStrings.'+key+'}"'
  s=re.sub(r'(Text|Content|Title|Header|PlaceholderText|ToolTip.Tip|AutomationProperties.Name)="([^"]+)"',replace,s)
  if 'tr:TriskoStrings.' in s and 'xmlns:tr=' not in s:
   s=s.replace('xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"','xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n    xmlns:tr="clr-namespace:ServiceLib.Trisko;assembly=ServiceLib"')
  p.write_text(s,encoding='utf-8')
code='// Generated by eng/localize-xaml.py. All labels share the product translation catalog.\nnamespace ServiceLib.Trisko;\n\npublic static class TriskoStrings\n{\n'
for key,value in sorted(strings.items()):
 code+='    public static string '+key+' => TriskoLocalization.Text('+json.dumps(value,ensure_ascii=False)+');\n'
code+='}\n'
(root/'v2rayN/ServiceLib/Trisko/TriskoStrings.cs').write_text(code,encoding='utf-8')
print(len(strings),'XAML labels localized')
